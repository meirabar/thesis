def plot_wt_vs_design_heatmaps(
    csv_path: str,
    outfile: str = None,
    title: str = None,
    mutated_positions=None,           # Iterable of ints (positions to box)
    wt_by_pos: dict = None,           # Optional: {pos: 'A'}
    wt_seq: str = None                # Optional: WT sequence string (1-based positions)
):
    df = pd.read_csv(csv_path)
    required = {"pos", "mut", "ddg_wt", "ddg_design"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"CSV missing required columns: {missing}")

    df = df[df["mut"].isin(AA_ORDER)].copy()
    positions = sorted(df["pos"].unique().tolist())

    # Build WT mapping per position
    wt_map = {}
    if "wt" in df.columns:
        tmp = df.dropna(subset=["wt"]).groupby("pos")["wt"].agg(lambda x: x.mode().iat[0] if not x.mode().empty else x.iloc[0])
        wt_map = tmp.to_dict()
    elif wt_by_pos is not None:
        wt_map = dict(wt_by_pos)
    elif wt_seq is not None:
        for p in positions:
            idx = int(p) - 1
            if 0 <= idx < len(wt_seq):
                wt_map[p] = wt_seq[idx]

    # Pivot to matrices (reindex to ensure consistent ordering)
    wt_pivot = (df.pivot_table(index="mut", columns="pos", values="ddg_wt", aggfunc="mean")
                  .reindex(index=AA_ORDER, columns=positions))
    design_pivot = (df.pivot_table(index="mut", columns="pos", values="ddg_design", aggfunc="mean")
                     .reindex(index=AA_ORDER, columns=positions))

    # Shared zero-centered color scale
    vals = np.concatenate([wt_pivot.values.ravel(), design_pivot.values.ravel()])
    vals = vals[~np.isnan(vals)]
    vmax = np.percentile(np.abs(vals), 99) if vals.size else 1.0
    norm = TwoSlopeNorm(vmin=-vmax, vcenter=0.0, vmax=vmax)

    fig, axes = plt.subplots(1, 2, figsize=(16, 6), constrained_layout=True)
    if title:
        fig.suptitle(title, fontsize=14, y=1.02)

    im0 = axes[0].imshow(wt_pivot.values, aspect="auto", norm=norm)
    axes[0].set_title("DDG (WT background)")
    axes[0].set_xlabel("Position")
    axes[0].set_ylabel("Mutant AA")
    axes[0].set_xticks(range(len(positions)))
    axes[0].set_xticklabels(positions, rotation=90, fontsize=8)
    axes[0].set_yticks(range(len(AA_ORDER)))
    axes[0].set_yticklabels(AA_ORDER)

    im1 = axes[1].imshow(design_pivot.values, aspect="auto", norm=norm)
    axes[1].set_title("DDG (Design background)")
    axes[1].set_xlabel("Position")
    axes[1].set_ylabel("")
    axes[1].set_xticks(range(len(positions)))
    axes[1].set_xticklabels(positions, rotation=90, fontsize=8)
    axes[1].set_yticks(range(len(AA_ORDER)))
    axes[1].set_yticklabels(AA_ORDER)

    # Boxes for mutated positions
    if mutated_positions is None:
        mutated_positions = []
    # mutated_positions is a list like ["G1M", "A34T", ...]
    def extract_pos(mut_str):
        # Extract digits from something like "G1M"
        return int("".join([c for c in mut_str if c.isdigit()]))

    mutated_positions = set(extract_pos(p) for p in mutated_positions)

    for p in mutated_positions:
        x = positions.index(p)
        rect_wt = Rectangle((x - 0.5, -0.5), 1.0, len(AA_ORDER), fill=False, edgecolor="black", linewidth=1.8)
        rect_ds = Rectangle((x - 0.5, -0.5), 1.0, len(AA_ORDER), fill=False, edgecolor="black", linewidth=1.8)
        axes[0].add_patch(rect_wt)
        axes[1].add_patch(rect_ds)

    # mark WT cells with 'x' if NaN
    for p in positions:
        wt_aa = wt_map.get(p, None)
        if wt_aa is None or wt_aa not in AA_ORDER:
            continue
        y = AA_ORDER.index(wt_aa)
        x = positions.index(p)
        if np.isnan(wt_pivot.iloc[y, x]):
            axes[0].scatter([x], [y], marker='x', s=30, c='black', linewidths=1.2, zorder=3)
        if np.isnan(design_pivot.iloc[y, x]):
            axes[1].scatter([x], [y], marker='x', s=30, c='black', linewidths=1.2, zorder=3)

    cbar = fig.colorbar(im1, ax=axes.ravel().tolist(), shrink=0.9, pad=0.02)
    cbar.set_label("DDG (negative = more stable)")

    if outfile:
        plt.savefig(outfile, dpi=300, bbox_inches="tight")
        plt.close(fig)
    else:
        plt.show()
