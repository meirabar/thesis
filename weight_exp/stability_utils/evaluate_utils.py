def fetch_and_extract_sequence(pdb_id: str, chain_id: str = "A") -> str:
    pdb_id = pdb_id.lower()
    pdbl = PDBList()
    pdb_file = pdbl.retrieve_pdb_file(pdb_id, pdir="pdb_cache", file_format="pdb")
    pdb_file = _ensure_pdb_unzipped(pdb_file)

    parser = PDBParser(QUIET=True)
    structure = parser.get_structure(pdb_id, pdb_file)
    model = structure[0]

    if chain_id not in model:
        raise ValueError(f"Chain {chain_id} not found in downloaded PDB {pdb_id}")

    chain = model[chain_id]
    residues = [res for res in chain if res.get_id()[0] == " "]
    seq = "".join(seq1(res.get_resname()) for res in residues)
    return seq


def extract_sequence_from_pdb(pdb_path: str, chain_id: str = "A") -> str:
    parser = PDBParser(QUIET=True)
    structure = parser.get_structure("design", pdb_path)
    model = structure[0]

    if chain_id not in model:
        raise ValueError(f"Chain {chain_id} not found in {pdb_path}")

    chain = model[chain_id]
    residues = [res for res in chain if res.get_id()[0] == " "]
    seq = "".join(seq1(res.get_resname()) for res in residues)
    return seq


